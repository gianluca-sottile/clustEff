test_that("FPCA on a B-spline basis", {
  tt <- seq(0, 1, length.out = 100)
  set.seed(2)
  X <- sapply(1:30, function(i) rnorm(1) * sin(2 * pi * tt) + rnorm(1, 0, 0.3) * cos(2 * pi * tt))
  f <- fpca_bspline(X, tt, nbasis = 12, nharmonics = 3)
  expect_equal(dim(f$scores), c(30, 3))
  expect_true(all(diff(f$values) <= 0))
  expect_gt(sum(f$varprop[1:2]), 0.99)
  # harmonics are orthonormal in L2
  expect_equal(crossprod(f$harmonics, f$gram %*% f$harmonics), diag(3), tolerance = 1e-8)
  # the Gram matrix integrates the constant: sum of all entries = length of the interval
  expect_equal(sum(f$gram), 1, tolerance = 1e-10)
})

test_that("FPCA agrees with fda::pca.fd", {
  skip_if_not_installed("fda")
  tt <- seq(0, 1, length.out = 100)
  set.seed(2)
  X <- sapply(1:30, function(i) rnorm(1) * sin(2 * pi * tt) + rnorm(1, 0, 0.3) * cos(2 * pi * tt))
  f <- fpca_bspline(X, tt, nbasis = 8, norder = 4, nharmonics = 2, lambda = 0)
  bs <- fda::create.bspline.basis(c(0, 1), nbasis = 8, norder = 4)
  fd <- fda::Data2fd(tt, X, bs, lambda = 0)
  pf <- fda::pca.fd(fd, nharm = 2)
  expect_equal(abs(f$scores), abs(pf$scores), tolerance = 1e-3, ignore_attr = TRUE)
  expect_equal(f$values, pf$values[1:2], tolerance = 1e-3)
})

test_that("fpcac recovers two groups and trims the outliers", {
  s <- sim_waves(m = c(10, 10), sd = 0.2)
  set.seed(3)
  X <- cbind(s$W, sapply(1:2, function(i) rnorm(length(s$t), 0, 0.2)))
  set.seed(1)
  fit <- fpcac(X, t = s$t, K = 2, nbasis = 10, alpha = 0.09)
  expect_s3_class(fit, "fpcac")
  expect_true(all(fit$clusters[21:22] == 0))
  expect_true(same_partition(fit$clusters[1:20], s$group))
  expect_output(print(fit), "trimmed curves: 2")
  expect_output(print(summary(fit)), "Clustering table")
  grDevices::pdf(NULL)
  on.exit(grDevices::dev.off())
  expect_silent(plot(fit))
  expect_silent(plot(fit, which = 1, polygon = FALSE))
})

test_that("opt.fpcac selects the number of clusters", {
  s <- sim_waves(m = c(8, 8, 8), sd = 0.2)
  set.seed(1)
  o <- opt.fpcac(s$W, t = s$t, k.max = 5, nbasis = 10, nstart = 10)
  expect_s3_class(o, "opt.fpcac")
  expect_equal(o$K.opt, 3)
  expect_true(is.na(o$criterion[1]))
  o2 <- opt.fpcac(s$W, t = s$t, k.max = 4, criterion = "wss", nbasis = 10, nstart = 5)
  expect_true(o2$K.opt %in% 2:4)
  expect_output(print(o), "Selected number of clusters: 3")
  o1 <- opt.fpcac(s$W, t = s$t, k.max = 3, nbasis = 10, nharmonics = 1, nstart = 5)
  expect_true(o1$K.opt %in% 1:3)
  grDevices::pdf(NULL)
  on.exit(grDevices::dev.off())
  expect_silent(plot(o))
})

